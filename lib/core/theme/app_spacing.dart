/// Layout spacing shared by the tab screens (Home/Calendar/Report).
class AppSpacing {
  AppSpacing._();

  /// Horizontal page gutter.
  static const double gutter = 20;

  /// Inner padding of a standalone section card.
  static const double cardPadding = 20;

  /// Inner padding of a list/grid item card.
  static const double itemPadding = 16;

  /// Vertical gap between stacked cards/sections.
  static const double sectionGap = 16;

  /// Bottom corner radius of the Calendar/Report header band.
  static const double headerBandRadius = 24;
}
